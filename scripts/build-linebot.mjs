// Builds linebot/LineBot.gs — the single file pasted into Apps Script:
// src/formulary.js (shared matcher) followed by linebot/bot.js.
// `--check` fails when the committed file is out of date (used by the tests).
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const header = `// 院內查藥 LINE Bot — generated by scripts/build-linebot.mjs; do not edit.
// Paste this whole file into the Apps Script editor of the formulary sheet.
// Source: src/formulary.js + linebot/bot.js
`;
const output =
  header +
  "\n" +
  (await readFile(join(root, "src", "formulary.js"), "utf8")) +
  "\n" +
  (await readFile(join(root, "linebot", "bot.js"), "utf8"));
const target = join(root, "linebot", "LineBot.gs");

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== output) {
    console.error("linebot/LineBot.gs is out of date — run: npm run build:linebot");
    process.exit(1);
  }
} else {
  await writeFile(target, output);
  console.log(`Built ${target}`);
}
