// Builds the two files pasted into Apps Script for the phone web app:
//   gas/Code.gs    = src/formulary.js + gas/server.js
//   gas/Index.html = gas/page.html with web/style.css + gas/page.css and
//                    src/formulary.js + gas/page.js inlined (HtmlService
//                    serves one file, so nothing can be linked).
// `--check` fails when the committed files are out of date (used by the tests).
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const root = process.cwd();
const read = (...parts) => readFile(join(root, ...parts), "utf8");

const [formulary, server, page, webCss, pageCss, pageJs] = await Promise.all([
  read("src", "formulary.js"),
  read("gas", "server.js"),
  read("gas", "page.html"),
  read("web", "style.css"),
  read("gas", "page.css"),
  read("gas", "page.js"),
]);

function inline(tag, body, source) {
  if (body.toLowerCase().includes(`</${tag}`)) {
    throw new Error(`${source} contains </${tag}> and can't be inlined`);
  }
  return `<${tag}>\n${body}\n</${tag}>`;
}

function replaceMarker(html, marker, replacement) {
  const token = `<!-- @${marker} -->`;
  if (!html.includes(token)) {
    throw new Error(`gas/page.html is missing ${token}`);
  }
  // A function replacement keeps "$" in the inlined code literal.
  return html.replace(token, () => replacement);
}

// Same id in both files, so the page can tell when Code.gs and Index.html
// were pasted from different versions.
const buildId = createHash("sha256")
  .update([formulary, server, page, webCss, pageCss, pageJs].join("\u0000"))
  .digest("hex")
  .slice(0, 7);

const banner = "院內查藥 · OE (Apps Script) — generated by scripts/build-gas.mjs; do not edit.";

const code = `// ${banner}
// Paste this whole file into Code.gs in the Apps Script editor of the formulary sheet.
// Source: src/formulary.js + gas/server.js

var OE_BUILD = "${buildId}";

${formulary}
${server}`;

let html = `<!-- ${banner}\n     Paste this whole file into an HTML file named Index in the Apps Script editor.\n     Source: gas/page.html + web/style.css + gas/page.css + src/formulary.js + gas/page.js -->\n${page}`;
if (!html.includes("__OE_BUILD__")) {
  throw new Error("gas/page.html is missing __OE_BUILD__");
}
html = html.replaceAll("__OE_BUILD__", buildId);
html = replaceMarker(html, "style", inline("style", `${webCss}\n${pageCss}`, "the stylesheets"));
html = replaceMarker(
  html,
  "script",
  `${inline("script", formulary, "src/formulary.js")}\n${inline("script", pageJs, "gas/page.js")}`,
);

const outputs = [
  [join(root, "gas", "Code.gs"), code],
  [join(root, "gas", "Index.html"), html],
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const [target, content] of outputs) {
    const current = await readFile(target, "utf8").catch(() => "");
    if (current !== content) {
      console.error(`${target} is out of date — run: npm run build:gas`);
      stale = true;
    }
  }
  if (stale) {
    process.exit(1);
  }
} else {
  for (const [target, content] of outputs) {
    await writeFile(target, content);
    console.log(`Built ${target}`);
  }
}
